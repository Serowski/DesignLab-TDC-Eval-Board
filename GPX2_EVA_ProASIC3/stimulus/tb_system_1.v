`timescale 1ns/100ps

module tb_system_1;

    // Clock parameters
    parameter CLK_5MHZ_PERIOD = 200;    // 5 MHz (200 ns)
    parameter TDC_CLK_PERIOD  = 10;     // 100 MHz LCLKOUT clock from TDC (10 ns)
    parameter SYSTEM_CLK_PERIOD = 20;   // 50 MHz system clock generated by PLL
    
    // UART parameters
    parameter UART_BAUD = 921_600;
    parameter CLK_PER_BIT = 50_000_000 / UART_BAUD;
    parameter BIT_PERIOD_NS = 1085;

    // Clock and control
    reg clk_5mhz;
    reg rx;
    reg spisdi;


    // Differential LVDS lines from TDC
    reg lclkoutp_tdc;
    reg lclkoutn_tdc;
    reg frame1p;
    reg frame1n;
    reg sdo1p;
    reg sdo1n;

    // Outputs
    wire tx;
    wire spisclko;
    wire spisdo;
    wire spiss;
    wire lclkinp_tdc;
    wire lclkinn_tdc;
    wire osc_en;

    // =================== DUT instance =======================
    top_m1 top_m1_0 (
        // Inputs
        .RX(rx),
        .SPISDI(spisdi),
        .CLK_X2_5MHz(clk_5mhz),
        .SDO1P(sdo1p),
        .SDO1N(sdo1n),
        .FRAME1P(frame1p),
        .FRAME1N(frame1n),
        .LCLKOUTP_TDC(lclkoutp_tdc),
        .LCLKOUTN_TDC(lclkoutn_tdc),

        // Outputs
        .TX(tx),
        .SPISCLKO(spisclko),
        .SPISDO(spisdo),
        .SPISS(spiss),
        .LCLKINP_TDC(lclkinp_tdc),
        .LCLKINN_TDC(lclkinn_tdc),
        .OSC_EN(osc_en)
    );
    
    // =================== Clock Generation =====================
    
    // Main 5 MHz clock to PLL FPGA (CLK_X2_5MHz)
    initial clk_5mhz = 1'b0;
    always #(CLK_5MHZ_PERIOD / 2) clk_5mhz = ~clk_5mhz;

    // 100 MHz LVDS clock from TDC (LCLKOUTP / LCLKOUTN)
    initial begin
        lclkoutp_tdc = 1'b0;
        lclkoutn_tdc = 1'b1;
    end
    always #(TDC_CLK_PERIOD / 2) begin
        lclkoutp_tdc = ~lclkoutp_tdc;
        lclkoutn_tdc = ~lclkoutp_tdc;
    end
    
    // System 50MHz clock 
    wire sys_clk = top_m1_0.PLL_clock_0_GLA;



    // =================== Test tasks ===========================

    // UART send byte - 921_600 baud ~= 1080ns gap 
    task send_uart_byte(input [7:0] data);
        integer i;
        begin
            // Start bit (0)
            rx = 1'b0;
            repeat (CLK_PER_BIT) @(posedge sys_clk);
            //#(BIT_PERIOD_NS);
            // 8 data bits (LSB first)
            for (i = 0; i < 8; i = i + 1) begin
                rx = data[i];
                repeat (CLK_PER_BIT) @(posedge sys_clk);
                //#(BIT_PERIOD_NS);
            end
            
            // Stop bit (1)
            rx = 1'b1;
            repeat (CLK_PER_BIT) @(posedge sys_clk);
            //#(BIT_PERIOD_NS);
            // Delay between bytes
            #2000;
        end
    endtask

    // Send 32-bit measurment FRAME from TDC 
    task send_tdc_frame(input [31:0] tdc_data);
        integer j;
        begin
            // FRAME and SDO bits are asserted on negative slope of LCLKOUT
            @(negedge lclkoutp_tdc);
            frame1p = 1'b1;
            frame1n = 1'b0;

            for (j = 31; j >= 0; j = j - 1) begin
                sdo1p = tdc_data[j];
                sdo1n = ~tdc_data[j];
                if(j == 23) begin
                    frame1p = 1'b0;
                    frame1n = 1'b1;
                end
                @(negedge lclkoutp_tdc);
            end

            // End of frame
            frame1p = 1'b0;
            frame1n = 1'b1;
            sdo1p   = 1'b0;
            sdo1n   = 1'b1;

            repeat (10) @(negedge lclkoutp_tdc);
        end
    endtask

    // Continuous stream measurment frames from TDC 
    task send_multi_frame();
        integer i;
        for(i=0; i < 300; i=i+1) begin
            send_tdc_frame(32'h12345678);
        end
    endtask

    // Send the config from TDC -> FPGA
    task send_config_from_TDC();
        integer i;
        begin
            for (i=0; i<(18*8); i = i+1) begin
                @(posedge spisclko);
                spisdi = i % 2;
            end
        end
    endtask

    // ================== Main program ===================
    initial begin
        // Inputs initialization
        rx      = 1'b1;
        spisdi  = 1'b0;
        frame1p = 1'b0;
        frame1n = 1'b1;
        sdo1p   = 1'b0;
        sdo1n   = 1'b1;
  

        // 1. Wait for PLL to stabilize and for RESETN
        wait(top_m1_0.PLL_clock_0_LOCK == 1'b1);
        @(posedge top_m1_0.COREABC_0_PRESETN);
        //#100000;

        // 2. Send config bytes to TDC 
        // FPGA: RX -> CoreUARTapb -> CoreABC -> CoreSPI -> SPI to TDC
        
        send_uart_byte(8'h30);      // Power on Reset
        send_uart_byte(8'h80);      // Write config
        send_uart_byte(8'hA0);      // 0 - 17 config regs
        send_uart_byte(8'hA1);
        send_uart_byte(8'hA2);
        send_uart_byte(8'hA3);
        send_uart_byte(8'hA4);
        send_uart_byte(8'hA5);
        send_uart_byte(8'hA6);
        send_uart_byte(8'hA7);
        send_uart_byte(8'hA8);
        send_uart_byte(8'hA9);
        send_uart_byte(8'hAA);
        send_uart_byte(8'hAB);
        send_uart_byte(8'hAC);
        send_uart_byte(8'hAD);
        send_uart_byte(8'hAE);
        send_uart_byte(8'hAF);
        send_uart_byte(8'hB0);
    
        send_uart_byte(8'h18);      // Init and start measurement

        
        send_tdc_frame(32'hEFEFEFEF);
        send_tdc_frame(32'h12121212);
        send_tdc_frame(32'h45454545);
        #300000;
        // 3. Stop measurement and read config
        send_uart_byte(8'h30);
        #100000;
        send_uart_byte(8'h40);
        send_config_from_TDC();
        // Wait for TX to send all config bytes
        #300000;



        //#300000;
        $stop;
    end

endmodule

